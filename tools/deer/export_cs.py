"""Writes OpenWorld/src/DeerModel.cs from the frozen build deer.json, since the mod ships only source.
python3 export_cs.py [deer.json] [out.cs]

Kept in the model's own frame (metres, Y up, facing +Z, the deer's left = +X, right-handed); DeerModel.cs turns it into Unity's
(left-handed: x mirrored, triangles' winding reversed, a pose's Y and Z turns negated) and scales it to game units when the mesh is
made, so this file stays a plain copy of deer.json. Poses are absolute local rotations as three angles applied as Rx.Ry.Rz (rot() in
deer.py)."""
import json, sys, os

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, 'deer.json')
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', '..', 'OpenWorld', 'src', 'DeerModel.cs')
D = json.load(open(src))
# The buck's antlers (antlers.py): rigid on one bone, their own texture (a gradient along v); the doe's arrays are left as they are.
A = json.load(open(os.path.join(here, 'antlers.json')))

def num(v):
	s = ('%.4f' % v).rstrip('0').rstrip('.')
	if s in ('-0', ''):
		s = '0'
	return s + 'f'

def floats(name, vals, per_line=24):
	lines = []
	for i in range(0, len(vals), per_line):
		lines.append('\t\t\t' + ', '.join(num(v) for v in vals[i:i + per_line]) + ',')
	return '\t\tinternal static readonly float[] %s =\n\t\t{\n%s\n\t\t};\n' % (name, '\n'.join(lines))

def ints(name, typ, vals, per_line=40):
	lines = []
	for i in range(0, len(vals), per_line):
		lines.append('\t\t\t' + ', '.join(str(int(v)) for v in vals[i:i + per_line]) + ',')
	return '\t\tinternal static readonly %s[] %s =\n\t\t{\n%s\n\t\t};\n' % (typ, name, '\n'.join(lines))

bones = D['bones']
names = [b['n'] for b in bones]
index = {n: i for i, n in enumerate(names)}

def mirror_name(n):
	if n.endswith('L'):
		return n[:-1] + 'R'
	if n.endswith('R'):
		return n[:-1] + 'L'
	return n

poses = dict(D['poses'])
# The walk's other step: the left and right legs swapped (and a turn about Y or Z mirrored with them).
poses['walk2'] = {mirror_name(k): [v[0], -v[1], -v[2]] for k, v in D['poses']['walk1'].items()}
pose_names = list(poses.keys())

parts = []
parts.append('// <auto-generated>\n// Written by tools/deer/export_cs.py from tools/deer/deer.json (the frozen build the texture templates fit) and antlers.json.\n// Do not edit by hand: change the model in tools/deer and run the exporter again.\n// </auto-generated>\n')
parts.append('namespace HalfGripOpenWorld\n{\n')
parts.append('\t/// <summary>\n\t/// The white-tailed deer\'s mesh, skeleton and poses as sculpted in <c>tools/deer</c>, in the model\'s own frame: metres, Y up, facing +Z,\n\t/// the deer\'s left = +X (right-handed). <see cref="DeerMesh"/> turns it into Unity\'s frame and game units. %d vertices, %d triangles,\n\t/// %d bones; each vertex has one colour region (%s) so a coat is a palette swap.\n\t/// </summary>\n' % (len(D['reg']), len(D['idx']) // 3, len(bones), ', '.join(D['regions'])))
parts.append('\tinternal static class DeerModel\n\t{\n')
parts.append('\t\t/// <summary>The colour regions, in the order <see cref="Region"/> numbers them.</summary>\n')
parts.append('\t\tinternal static readonly string[] Regions = { %s };\n\n' % ', '.join('"%s"' % r for r in D['regions']))
for pal in ('palette', 'winter'):
	cname = 'Summer' if pal == 'palette' else 'Winter'
	parts.append('\t\t/// <summary>The %s coat: one 0xRRGGBB colour per region.</summary>\n' % cname.lower())
	parts.append('\t\tinternal static readonly int[] %s = { %s };\n\n' % (cname, ', '.join('0x%06X' % D[pal][r] for r in D['regions'])))
parts.append('\t\t/// <summary>Bone names, parents (-1 for the hips) and offsets from the parent (x, y, z in metres); bind rotations are all zero.</summary>\n')
parts.append('\t\tinternal static readonly string[] BoneNames = { %s };\n' % ', '.join('"%s"' % n for n in names))
parts.append('\t\tinternal static readonly int[] BoneParents = { %s };\n' % ', '.join(str(index[b['p']]) if b['p'] else '-1' for b in bones))
parts.append(floats('BoneOffsets', [c for b in bones for c in b['o']], 30) + '\n')
parts.append('\t\t/// <summary>The poses\' names (walk2 is walk1 with the legs swapped, made by the exporter).</summary>\n')
parts.append('\t\tinternal static readonly string[] PoseNames = { %s };\n\n' % ', '.join('"%s"' % n for n in pose_names))
pose_vals = []
for p in pose_names:
	for n in names:
		pose_vals.extend(poses[p].get(n, [0.0, 0.0, 0.0]))
parts.append('\t\t/// <summary>Per pose, per bone: its absolute local rotation as three angles in radians, applied as Rx.Ry.Rz (zero: as bound).</summary>\n')
parts.append(floats('Poses', pose_vals, 30) + '\n')
parts.append('\t\t/// <summary>Vertex positions and normals (x, y, z each).</summary>\n')
parts.append(floats('Positions', D['pos']) + '\n')
parts.append(floats('Normals', D['nor']) + '\n')
parts.append('\t\t/// <summary>Each vertex\'s colour region.</summary>\n')
parts.append(ints('Region', 'byte', D['reg'], 60) + '\n')
parts.append('\t\t/// <summary>The painted texture\'s UVs (u, v each), for when there is one (texture/ in tools/deer).</summary>\n')
parts.append(floats('Uvs', D['uv']) + '\n')
parts.append('\t\t/// <summary>Each vertex\'s four bones and their weights (summing to one).</summary>\n')
parts.append(ints('BoneIndex', 'byte', D['bi'], 60) + '\n')
parts.append(floats('BoneWeight', D['bw']) + '\n')
parts.append('\t\t/// <summary>Triangles (three vertices each, counter-clockwise seen from outside in the model\'s right-handed frame).</summary>\n')
parts.append(ints('Triangles', 'ushort', D['idx']) + '\n')
parts.append('\t\t/// <summary>The buck\'s antlers (tools/deer/antlers.py), put on the doe\'s mesh for a buck: %d vertices, %d triangles, all on one bone.</summary>\n' % (len(A['v']), len(A['idx']) // 3))
parts.append('\t\tinternal const int AntlerBone = %d;\n\n' % index[A['bone']])
parts.append(floats('AntlerPositions', A['pos']) + '\n')
parts.append(floats('AntlerNormals', A['nor']) + '\n')
parts.append('\t\t/// <summary>Per antler vertex: how far from the burr (0) to the tips (1), the antler texture\'s v.</summary>\n')
parts.append(floats('AntlerShade', A['v']) + '\n')
parts.append('\t\t/// <summary>The antlers\' triangles (counter-clockwise seen from outside, as <see cref="Triangles"/>).</summary>\n')
parts.append(ints('AntlerTriangles', 'ushort', A['idx']))
parts.append('\t}\n}\n')
with open(out, 'w', newline='\n') as f:
	f.write(''.join(parts))
print('wrote', out, '%d vertices, %d triangles, %d bones, %d poses' % (len(D['reg']), len(D['idx']) // 3, len(bones), len(pose_names)))
